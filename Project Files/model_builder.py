import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, BatchNormalization, LeakyReLU, MaxPooling2D, GlobalAveragePooling2D, Dense, Dropout

def build_model():
    model = Sequential()
    model.add(Conv2D(filters=16, kernel_size=[7, 7], strides=[1, 1], padding='same', use_bias=False, input_shape=(100, 100, 3)))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(Conv2D(filters=32, kernel_size=[5, 5], strides=[1, 1], padding='valid', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(MaxPooling2D(pool_size=[2, 2], strides=[2, 2], padding='valid'))
    model.add(Conv2D(filters=32, kernel_size=[7, 7], strides=[1, 1], padding='same', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(Conv2D(filters=64, kernel_size=[5, 5], strides=[1, 1], padding='valid', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(MaxPooling2D(pool_size=[2, 2], strides=[2, 2], padding='valid'))
    model.add(Conv2D(filters=128, kernel_size=[5, 5], strides=[1, 1], padding='valid', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(Conv2D(filters=256, kernel_size=[3, 3], strides=[1, 1], padding='valid', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(MaxPooling2D(pool_size=[2, 2], strides=[2, 2], padding='valid'))
    model.add(Conv2D(filters=256, kernel_size=[3, 3], strides=[1, 1], padding='valid', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(Conv2D(filters=512, kernel_size=[3, 3], strides=[1, 1], padding='valid', use_bias=False))
    model.add(BatchNormalization(axis=3, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(GlobalAveragePooling2D())
    model.add(Dense(units=256, use_bias=False, activation='linear'))
    model.add(BatchNormalization(axis=1, momentum=0.99, epsilon=0.001))
    model.add(LeakyReLU(alpha=0.10000000149011612))
    model.add(Dropout(rate=0.2))
    model.add(Dense(units=8, use_bias=True, activation='softmax'))
    return model
